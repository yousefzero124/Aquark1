const Lang = {
  get() {
    try { return localStorage.getItem("aqarak_lang") === "en" ? "en" : "ar"; }
    catch (e) { return "ar"; }
  },
  set(lang) {
    try { localStorage.setItem("aqarak_lang", lang); } catch (e) { /* ignore */ }
  },
  toggle() {
    this.set(this.get() === "ar" ? "en" : "ar");
    location.reload();
  },
};

/** يرجّع النص المترجم للمفتاح، مع استبدال {متغيرات} */
function t(key, vars) {
  const lang = Lang.get();
  let str = (I18N[lang] && I18N[lang][key]) ?? I18N.ar[key] ?? key;
  if (vars) {
    Object.keys(vars).forEach((k) => { str = str.split(`{${k}}`).join(vars[k]); });
  }
  return str;
}

/** يرجّع القيمة باللغة الحالية لو كانت {ar, en} */
function loc(value) {
  if (value && typeof value === "object") return value[Lang.get()] ?? value.ar ?? "";
  return value ?? "";
}

/** يطبّق الترجمة على كل العناصر اللي عليها data-i18n */
function applyI18n(root = document) {
  const lang = Lang.get();
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  root.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll("[data-i18n-ph]").forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
  root.querySelectorAll("[data-i18n-aria]").forEach((el) => { el.setAttribute("aria-label", t(el.dataset.i18nAria)); });
  const titleKey = document.body && document.body.dataset.title;
  if (titleKey) document.title = t(titleKey);
}
